-- Phase 2: Supabase Postgres schema for Morrow Objects
-- This file is the canonical migration for the current app data model.
-- It keeps the API contract stable while translating the SQLite schema to Postgres-safe types.

create extension if not exists pgcrypto;

create type public.user_role as enum ('customer', 'admin', 'seller');
create type public.user_status as enum ('active', 'suspended', 'deleted');
create type public.login_event_type as enum (
  'login_success',
  'login_failure',
  'logout',
  'password_reset_requested',
  'password_reset_completed'
);
create type public.order_status as enum ('placed', 'paid', 'fulfilled', 'cancelled');
create type public.seller_submission_status as enum ('pending', 'approved', 'rejected');

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null,
  phone text not null default '',
  address text not null default '',
  password_hash text not null,
  role public.user_role not null default 'customer',
  status public.user_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.users add column if not exists phone text not null default '';
alter table public.users add column if not exists address text not null default '';

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  revoked_at timestamptz null
);

create table if not exists public.password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users (id) on delete cascade,
  token_hash text not null unique,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  used_at timestamptz null
);

create table if not exists public.login_activity (
  id bigint generated by default as identity primary key,
  user_id bigint null references public.users (id) on delete set null,
  email text not null,
  event_type public.login_event_type not null,
  success boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text not null,
  category text not null,
  price_cents integer not null check (price_cents >= 0),
  image_url text not null,
  image_alt text not null,
  meta text not null default '',
  tag text not null default '',
  published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  public_order_number text not null unique,
  user_id bigint not null references public.users (id),
  status public.order_status not null default 'placed',
  total_cents integer not null check (total_cents >= 0),
  shipping_json jsonb not null default '{}'::jsonb,
  receipt_number text not null unique,
  payment_method text not null,
  card_last4 text null,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  product_id bigint null references public.products (id),
  product_name text not null,
  unit_price_cents integer not null check (unit_price_cents >= 0),
  quantity integer not null check (quantity > 0)
);

create table if not exists public.seller_submissions (
  id bigint generated by default as identity primary key,
  user_id bigint null references public.users (id) on delete set null,
  seller_email text not null,
  product_json jsonb not null default '{}'::jsonb,
  status public.seller_submission_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_users_email on public.users (email);
create index if not exists idx_sessions_user_expires on public.sessions (user_id, expires_at, revoked_at);
create index if not exists idx_sessions_token_hash on public.sessions (token_hash);
create index if not exists idx_login_activity_user_created on public.login_activity (user_id, created_at desc);
create index if not exists idx_products_catalog on public.products (published, category, sort_order, id);
create index if not exists idx_products_slug on public.products (slug);
create index if not exists idx_orders_user_created on public.orders (user_id, created_at desc);
create index if not exists idx_orders_public_number on public.orders (public_order_number);
create index if not exists idx_order_items_order on public.order_items (order_id);
create index if not exists idx_seller_submissions_status on public.seller_submissions (status, created_at desc);

